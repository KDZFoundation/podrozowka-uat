const fetchBytes = async (url) => {
  const response = await fetch(url, { redirect: "error" });
  if (!response.ok) throw new Error(`font_registry_fetch_failed:${response.status}:${url}`);
  if (response.headers.get("content-type")?.split(";", 1)[0].trim().toLowerCase() !== "font/woff2") {
    throw new Error(`font_registry_content_type_invalid:${url}`);
  }
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (new TextDecoder("ascii").decode(bytes.slice(0, 4)) !== "wOF2") {
    throw new Error(`font_registry_woff2_invalid:${url}`);
  }
  return bytes;
};

const normalizeSubset = (key) => key.replace(/^\[/, "").replace(/\]$/, "");
const fontUrl = (definition, subset) => {
  const file = definition.static
    ? `${definition.slug}-${subset}-400-normal.woff2`
    : `${definition.slug}-${subset}-wght-normal.woff2`;
  return `${CDN_ROOT}/${definition.package}@${VERSION}/files/${file}`;
};

const pending = [];
for (const definition of collections) {
  const metadataUrl = `${CDN_ROOT}/${definition.package}@${VERSION}/unicode.json`;
  const response = await fetch(metadataUrl, { redirect: "error" });
  if (!response.ok) throw new Error(`font_registry_unicode_failed:${response.status}:${metadataUrl}`);
  const unicode = await response.json();
  for (const [rawSubset, unicodeRange] of Object.entries(unicode)) {
    const subset = normalizeSubset(rawSubset);
    pending.push({ definition, subset, unicodeRange, url: fontUrl(definition, subset) });
  }
}

const results = [];
const workers = Array.from({ length: 12 }, async () => {
  while (pending.length) {
    const item = pending.shift();
    if (!item) return;
    const bytes = await fetchBytes(item.url);
    results.push({
      key: `${item.definition.id}-${item.subset}`,
      collection: item.definition.id,
      family: item.definition.family,
      weight: item.definition.weight,
      style: "normal",
      unicode_range: item.unicodeRange,
      source_url: item.url,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    });
  }
});
await Promise.all(workers);
results.sort((left, right) => left.key.localeCompare(right.key));

const output = `/* This file is generated by scripts/generate-pod-font-registry.mjs.\n`
  + ` * Fontsource packages are pinned to ${VERSION}; every WOFF2 is verified by SHA-256 at freeze time.\n`
  + ` * Do not edit this file manually.\n */\n`
  + `export const POD_FONT_REGISTRY_VERSION = "fontsource-5.3.0-v1" as const;\n\n`
  + `export const POD_FONT_REGISTRY = ${JSON.stringify(results, null, 2)} as const;\n`;

await writeFile(path.join(projectRoot, "src/lib/podFontRegistry.generated.ts"), output, "utf8");
console.log(`Generated ${results.length} pinned POD font subsets.`);
